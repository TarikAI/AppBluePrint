"""views.features_md: FEATURES.md, the views hook of the features module (contract 8.2).

Reads ctx only (ctx["features"] is filled by bp.features.context). The file exists only when the plan has features.
Per feature, in plan order: heading with glyph, id, title and status (with the awaiting-evaluation count of 4.3), the
statement, `kind · milestone · owner · level`, what it depends on, its files, a criteria table, the latest evaluation,
the unknowns blocking it and the study it came from. Drafts come last, under `## Drafts`.
"""
import re

from bp.features import FEATURE_GLYPH, FEATURE_STATES, check_text
from bp.plan import GLYPH

HEADER = "<!-- Generated by blueprint.py render. Do not edit. -->"


def _one_line(v):
    return re.sub(r"\s+", " ", str(v if v is not None else "")).strip()


def _cell(v):
    return _one_line(v).replace("|", "\\|")


def _evaluation_cell(c):
    """The Evaluation column: what the independent evaluation says about this criterion."""
    if c["verify"]:  # a command criterion: only a recorded fail or note from an evaluation is shown
        return c["evaluation"] or "-"
    if c["stale"]:
        return "stale"
    if c["result"] == "pass" and c["via"] == "evaluation":
        return "pass" + (f" ({c['resultLevel']})" if c.get("resultLevel") else "")
    if c["evaluation"] and c["evaluation"] != "pass":
        return c["evaluation"]
    return "unknown"


def _check_cell(c):
    return check_text(c) if c["verify"] else "-"


def _file_lines(plan, f):
    """Planned files as `glyph path`, each pattern once as `glyph ⟨pattern id⟩ glob (N on disk)`."""
    pats = {p.get("id"): p for p in plan.get("patterns") or [] if isinstance(p, dict)}
    lines, grouped = [], {}
    for it in f["items"]:
        if it["from"] == "file":
            lines.append(f"- {GLYPH.get(it['status'], '?')} `{it['path']}`")
        else:
            grouped.setdefault(it["from"][len("pattern:"):], []).append(it)
    rank = list(GLYPH)
    for pid in sorted(grouped):
        glob = (pats.get(pid) or {}).get("glob") or grouped[pid][0]["path"]
        on_disk = [i for i in grouped[pid] if i["path"] != glob]
        low = min((i["status"] for i in grouped[pid]), key=lambda s: rank.index(s) if s in rank else 0)
        lines.append(f"- {GLYPH.get(low, '?')} ⟨pattern {pid}⟩ `{glob}` ({len(on_disk)} on disk)")
    return lines or ["- none yet: add this feature's id to files[].features"]


def _feature_lines(plan, f, level):
    h = "#" * level
    lines = [f"{h} {FEATURE_GLYPH[f['status']]} {f['id']} {_one_line(f['title'])} · {f['statusText']}", ""]
    if f["statement"]:
        lines += [_one_line(f["statement"]), ""]
    lines += [f"{f['kind']} · {f['milestone'] or 'no milestone'} · {f['owner']} · {f['level']}", ""]
    lines.append("Depends on: " + (", ".join(f["dependsOn"]) or "none"))
    lines.append("")
    lines.append("Files:")
    lines.append("")
    lines += _file_lines(plan, f)
    lines.append("")
    if f["criteria"]:
        lines += ["| ID | Given | When | Then | Must not | Level | Check | Evaluation |", "|---|---|---|---|---|---|---|---|"]
        for c in f["criteria"]:
            lines.append(f"| {_cell(c['id'])} | {_cell(c['scenario'])} | {_cell(c['action'])} | {_cell(c['expected'])} | "
                         f"{_cell(c['mustNot'])} | {_cell(c['level'])} | {_cell(_check_cell(c))} | "
                         f"{_cell(_evaluation_cell(c))} |")
    else:
        lines.append("No acceptance criteria yet.")
    lines.append("")
    ev = f["evaluation"]
    if ev:
        lines.append(f"Latest evaluation: {_one_line(ev['by'])} · {_one_line(ev['mode'])} · {_one_line(ev['verdict'])}"
                     f" · {_one_line(str(ev['at'] or '')[:10])}")
    else:
        lines.append("Latest evaluation: none")
    lines.append("")
    if f["blockedBy"]:
        lines += ["Blocked by: " + ", ".join(f["blockedBy"]), ""]
    if f["source"] and f["source"].get("study"):
        lines += [f"Source: study {_one_line(f['source']['study'])}", ""]
    return lines


def views(ctx):
    feats = [f for f in ctx.get("features") or [] if isinstance(f, dict)]
    if not feats:
        return {}
    plan = ctx["plan"]
    app = (plan.get("app") or {}).get("name") or "App"
    live = [f for f in feats if not f["draft"]]
    drafts = [f for f in feats if f["draft"]]
    counts = {s: sum(1 for f in feats if f["status"] == s) for s in FEATURE_STATES}
    lines = [f"# {_one_line(app)} features", HEADER,
             f"Features: accepted {counts['accepted']} of {len(live)}"
             + (f" · drafts: {len(drafts)}" if drafts else "") + " · "
             + (", ".join(f"{FEATURE_GLYPH[s]} {counts[s]} {s}" for s in FEATURE_STATES if counts[s])), ""]
    for f in live:
        lines += _feature_lines(plan, f, 2)
    if drafts:
        lines += ["## Drafts", ""]
        for f in drafts:
            lines += _feature_lines(plan, f, 3)
    return {"FEATURES.md": "\n".join(lines).rstrip("\n") + "\n"}
