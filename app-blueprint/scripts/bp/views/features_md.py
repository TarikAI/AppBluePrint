"""views.features_md: FEATURES.md, the views hook of the features module (contract 8.2).

Reads ctx only (ctx["features"] is filled by bp.features.context). The file exists only when the plan has features.
Per feature, in plan order: heading with glyph, id, title and status (with the awaiting-evaluation count of 4.3), the
statement, `kind · milestone · owner · level`, what it depends on, its files, a criteria table, the latest evaluation,
the unknowns blocking it and the study it came from. Drafts come last, under `## Drafts`.

Text safety: every value the plan supplies is put on one line (runs of whitespace, newlines included, collapse to one
space), `<` and `&` are escaped so raw HTML never passes through, `|` is escaped in table cells and a path is fenced
with a longer backtick run than it contains, so a field cannot start a heading, a table row or a tag.
"""
import re

from bp.features import FEATURE_GLYPH, FEATURE_STATES, FILE_RANK
from bp.plan import GLYPH

HEADER = "<!-- Generated by blueprint.py render. Do not edit. -->"


def _flat(v):
    return re.sub(r"\s+", " ", str(v if v is not None else "")).strip()


def _t(v):
    """One line of text with `&` and `<` escaped."""
    return _flat(v).replace("&", "&amp;").replace("<", "&lt;")


def _cell(v):
    return _t(v).replace("|", "\\|")


def _para(v):
    """A paragraph line that cannot start a heading, quote, list item, table row or rule."""
    text = _t(v)
    return "\\" + text if re.match(r"(#|>|-|\*|\+|\||\d+[.)]|=|~|`)", text) else text


def _code(v):
    """A code span for a path or glob, fenced with more backticks than the text holds."""
    text = _flat(v)
    run = max((len(m) for m in re.findall(r"`+", text)), default=0)
    pad = " " if text.startswith("`") or text.endswith("`") else ""
    return f"{'`' * (run + 1)}{pad}{text}{pad}{'`' * (run + 1)}"


def _file_lines(patterns, f):
    """Planned files as `glyph path`, each pattern once as `glyph ⟨pattern id⟩ glob (N on disk)`. A pattern's glyph
    is blocked when any instance is, else the lowest status among its instances."""
    lines, grouped = [], {}
    for it in f["items"]:
        if it["from"] == "file":
            lines.append(f"- {GLYPH.get(it['status'], '?')} {_code(it['path'])}")
        else:
            grouped.setdefault(it["from"][len("pattern:"):], []).append(it)
    for pid in sorted(grouped):
        glob = patterns.get(pid) or grouped[pid][0]["path"]
        on_disk = [i for i in grouped[pid] if i["path"] != glob]
        statuses = [i["status"] for i in grouped[pid]]
        low = "blocked" if "blocked" in statuses else min(statuses, key=lambda s: FILE_RANK.get(s, 0))
        lines.append(f"- {GLYPH.get(low, '?')} ⟨pattern {_t(pid)}⟩ {_code(glob)} ({len(on_disk)} on disk)")
    return lines or ["- none yet: add this feature's id to files[].features"]


def _feature_lines(patterns, f, level):
    h = "#" * level
    lines = [f"{h} {FEATURE_GLYPH[f['status']]} {_t(f['id'])} {_t(f['title'])} · {_t(f['statusText'])}", ""]
    if f["statement"]:
        lines += [_para(f["statement"]), ""]
    lines += [f"{_t(f['kind'])} · {_t(f['milestone'] or 'no milestone')} · {_t(f['owner'])} · {_t(f['level'])}", ""]
    lines.append("Depends on: " + (", ".join(_t(d) for d in f["dependsOn"]) or "none"))
    lines.append("")
    lines.append("Files:")
    lines.append("")
    lines += _file_lines(patterns, f)
    lines.append("")
    if f["criteria"]:
        lines += ["| ID | Given | When | Then | Must not | Level | Check | Evaluation |", "|---|---|---|---|---|---|---|---|"]
        for c in f["criteria"]:
            lines.append(f"| {_cell(c['id'])} | {_cell(c['scenario'])} | {_cell(c['action'])} | {_cell(c['expected'])} | "
                         f"{_cell(c['mustNot'])} | {_cell(c['level'])} | {_cell(c['checkText'])} | "
                         f"{_cell(c['evaluationText'])} |")
    else:
        lines.append("No acceptance criteria yet.")
    lines.append("")
    ev = f["evaluation"]
    if ev:
        lines.append(f"Latest evaluation: {_t(ev['by'])} · {_t(ev['mode'])} · {_t(ev['verdict'])}"
                     f" · {_t(str(ev['at'] or '')[:10])}")
    else:
        lines.append("Latest evaluation: none")
    lines.append("")
    if f["blockedBy"]:
        lines += ["Blocked by: " + ", ".join(_t(u) for u in f["blockedBy"]), ""]
    if f["source"] and f["source"].get("study"):
        lines += [f"Source: study {_t(f['source']['study'])}", ""]
    return lines


def views(ctx):
    feats = [f for f in ctx.get("features") or [] if isinstance(f, dict)]
    if not feats:
        return {}
    plan = ctx["plan"]
    patterns = {p.get("id"): p.get("glob") for p in plan.get("patterns") or [] if isinstance(p, dict)}
    app = (plan.get("app") or {}).get("name") or "App"
    live = [f for f in feats if not f["draft"]]
    drafts = [f for f in feats if f["draft"]]
    counts = {s: sum(1 for f in feats if f["status"] == s) for s in FEATURE_STATES}
    lines = [f"# {_t(app)} features", HEADER,
             f"Features: accepted {counts['accepted']} of {len(live)}"
             + (f" · drafts: {len(drafts)}" if drafts else "") + " · "
             + (", ".join(f"{FEATURE_GLYPH[s]} {counts[s]} {s}" for s in FEATURE_STATES if counts[s])), ""]
    for f in live:
        lines += _feature_lines(patterns, f, 2)
    if drafts:
        lines += ["## Drafts", ""]
        for f in drafts:
            lines += _feature_lines(patterns, f, 3)
    return {"FEATURES.md": "\n".join(lines).rstrip("\n") + "\n"}
