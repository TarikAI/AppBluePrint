"""views.roadmap_md: ROADMAP.md (contract 8.1). Reads ctx only; exists when the plan has milestones or tasks.

Layout: title, the generated header, one summary line; a section per milestone (in plan order) with its features and
tasks; "Not in a milestone"; "Open questions"; "Timeline". Features count only when they are not drafts, and only
`accepted` ones count as done (4.3).
"""
from bp import roadmap
from bp.roadmap import cell, criteria_passing, feature_status_text, line as _line


def _feature_table(feats):
    out = ["| Feature | Status | Criteria passing | Owner |", "|---|---|---|---|"]
    for f in feats:
        ok, total = criteria_passing(f)
        out.append(f"| {cell(str(f['id']) + ' ' + str(f.get('title') or ''))} | {cell(feature_status_text(f))} "
                   f"| {ok} of {total} | {cell(f.get('owner') or '')} |")
    return out


def _task_table(tasks):
    out = ["| Task | Owner | Status |", "|---|---|---|"]
    for t in tasks:
        status = t["status"] + (f" ({t['note']})" if t["status"] == "blocked" and t.get("note") else "")
        out.append(f"| {cell(t['id'] + ' ' + t['title'] + (' (you)' if t['ownerAction'] else ''))} | {cell(t['owner'])} "
                   f"| {cell(status)} |")
    return out


def _blocker(ctx, uid):
    u = next((x for x in roadmap.open_questions(ctx) if x["id"] == uid), None)
    return f"{uid} ({u.get('severity')}, {u.get('status')})" if u else uid


def views(ctx):
    plan = ctx.get("plan") or {}
    ms, ts = ctx.get("milestones") or [], ctx.get("tasks") or []
    if not ms and not ts:
        return {}
    feats = roadmap.feature_rows(plan, ctx)
    c = roadmap.counts(ctx)
    name = _line((plan.get("app") or {}).get("name") or "") or "App"
    out = [f"# {name} roadmap", "<!-- Generated by blueprint.py render. Do not edit. -->",
           f"Milestones: {c['milestones']} (done {c['milestonesDone']}) · Features: accepted {c['featuresAccepted']} of "
           f"{c['features']} · Tasks: done {c['tasksDone']} of {c['tasks']} · Open blocking questions: {c['blocking']}"]
    for m in ms:
        mf = [f for f in feats if f.get("milestone") == m["id"]]
        mt = [t for t in ts if t["milestone"] == m["id"]]
        head = f"## {_line(m['id'])} {_line(m['name'])}" + (f" · due {_line(m['due'])}" if m["due"] else "") + " · " + roadmap.progress_text(m)
        out += ["", head + (" · done" if m["done"] else "") + (" · overdue" if m["overdue"] else "")]
        goal = [x for x in (f"Goal: {_line(m['goal'])}" if m["goal"] else "", f"Exit: {_line(m['exit'])}" if m["exit"] else "") if x]
        if goal:
            out.append(" · ".join(goal))
        if mf:
            out += [""] + _feature_table(mf)
        if mt:
            out += [""] + _task_table(mt)
        blockers = list(dict.fromkeys(m["blockedBy"] + [u for f in mf for u in (f.get("blockedBy") or []) if isinstance(u, str)]))
        if blockers:
            out += ["", "Blocked by: " + ", ".join(_line(_blocker(ctx, u)) for u in blockers)]
    known = {m["id"] for m in ms}
    loose_f = [f for f in feats if f.get("milestone") not in known]
    loose_t = [t for t in ts if t["milestone"] not in known]
    if loose_f or loose_t:
        out += ["", "## Not in a milestone"]
        if loose_f:
            out += [""] + _feature_table(loose_f)
        if loose_t:
            out += [""] + _task_table(loose_t)
    qs = roadmap.open_questions(ctx)
    if qs:
        out += ["", "## Open questions", "", "| Unknown | Severity | Status | Blocks | Experiment | Evidence |",
                "|---|---|---|---|---|---|"]
        for u in qs:
            exp = u.get("experiment") if isinstance(u.get("experiment"), dict) else {}
            exps = ", ".join(x for x in (str(exp.get("timebox") or ""), f"exit: {exp['exit']}" if exp.get("exit") else "") if x)
            n_for = len(u["evidenceFor"]) if isinstance(u.get("evidenceFor"), list) else 0
            n_against = len(u["evidenceAgainst"]) if isinstance(u.get("evidenceAgainst"), list) else 0
            blocks = ", ".join(x for x in (u.get("blocks") or []) if isinstance(x, str)) if isinstance(u.get("blocks"), list) else ""
            out.append(f"| {cell(u['id'] + ' ' + str(u.get('question') or ''))} | {cell(u.get('severity') or '')} "
                       f"| {cell(u.get('status') or '')} | {cell(blocks)} | {cell(exps)} | for {n_for} / against {n_against} |")
    dated = sorted((m for m in ms if roadmap.is_date(m["due"])), key=lambda m: m["due"])  # stable: plan order within a day
    if dated:
        out += ["", "## Timeline", ""]
        if roadmap._syncd(ctx.get("state") or {}) is None:  # overdue is relative to syncedAt, so say when there is none
            out += ["Not synced yet: overdue is not shown.", ""]
        out += ["| Due | Milestone | Status |", "|---|---|---|"]
        for m in dated:
            out.append(f"| {m['due']} | {cell(m['id'] + ' ' + m['name'])} | " + ("done" if m["done"] else "overdue" if m["overdue"] else "open") + " |")
    return {"ROADMAP.md": "\n".join(out) + "\n"}
