"""views.roster: ROSTER.md, moved from blueprint.py 1.3.0 (contract 1.5), with the 2.0 sections of 8.3."""
import io

from bp import registry
from bp.plan import GLYPH, owner_of
from bp.data import data_view
from bp.views.structure import md_cell


def text_cell(s):
    """A plain (not code) table cell for a version 2 plan: one line, the backslash escaped before the pipe, so a value
    ending in a backslash cannot escape the cell's closing pipe. A version 1 plan keeps 1.3.0's bytes (md_cell, or the
    raw value where 1.3.0 wrote it raw)."""
    return " ".join(str(s if s is not None else "").split()).replace("\\", "\\\\").replace("|", "\\|")


def render_roster(plan, state, comp, ctx=None):
    rows, pats = comp["rows"], comp["patterns"]
    v1 = plan.get("_from") == 1 or plan.get("version") == 1
    raw = (lambda s: s) if v1 else text_cell  # what 1.3.0 wrote raw
    cell = md_cell if v1 else text_cell
    out = io.StringIO()
    w = out.write
    w(f"# {plan['app'].get('name')}: roster\n\n<!-- Generated by blueprint.py render. Do not edit. -->\n\n")
    w("Ownership follows the rules below in order; **the last matching rule wins**, as in CODEOWNERS. "
      "Write only files you own. Run `python .blueprint/bin/blueprint.py owner <path>` when unsure.\n\n")
    w("## Who\n\n| Owner | Kind | Harness | Role | Files | Verified | Patterns |\n|---|---|---|---|---|---|---|\n")
    for r in plan["roster"]:
        mine = [x for x in rows if x["owner"] == r["id"]]
        w(f"| {raw(r['id'])} | {raw(r.get('kind'))} | {cell(r.get('harness'))} | {cell(r.get('role'))} | {len(mine)} | "
          f"{sum(1 for x in mine if x['status'] == 'verified')} | {sum(1 for p in pats if p['owner'] == r['id'])} |\n")
    w("\n## Owner rules (last match wins)\n\n| # | Pattern | Owner | Override | Wins |\n|---|---|---|---|---|\n")
    for i, rule in enumerate(plan["owners"]):
        wins = sum(1 for x in rows if x["rule"] == i) + sum(1 for p in pats if p["rule"] == i)
        w(f"| {i + 1} | `{md_cell(rule.get('pattern'))}` | {raw(rule.get('owner'))} | {'yes' if rule.get('override') else ''} | {wins} |\n")
    if plan["resources"]:
        dv = data_view(plan, state)
        w("\n## Data ownership\n\nThe owner of a table is the owner of the file that defines it (or `owner` in the blueprint). Writes by anyone else need that owner's review.\n\n")
        w("| Resource | Kind | Owner | Writers from other owners |\n|---|---|---|---|\n")
        for r in dv["resources"]:
            foreign = [x for x in r["writers"] if owner_of(plan, x)[0] not in (None, r["owner"])]
            w(f"| {raw(r['id'])} | {raw(r['kind'])} | {cell(r['owner'])} | {cell(', '.join('`' + x + '` (' + str(owner_of(plan, x)[0]) + ')' for x in foreign))} |\n")
    w("\n## Write lists by owner and phase\n\n")
    for r in plan["roster"]:
        mine = [x for x in rows if x["owner"] == r["id"]]
        mp = [p for p in pats if p["owner"] == r["id"]]
        if not mine and not mp:
            continue
        w(f"### {r['id']}\n\n")
        for ph in plan["phases"]:
            fs = [x for x in mine if x["phase"] == ph["id"]]
            ps = [p for p in mp if p["phase"] == ph["id"]]
            if not fs and not ps:
                continue
            w(f"**{ph['id']} {ph.get('name', '')}**\n\n")
            for x in fs:
                w(f"- {GLYPH[x['status']]} `{x['path']}`{' ★' if x['contract'] else ''}{'' if x['action'] == 'create' else ' (' + x['action'] + ')'}\n")
            for p in ps:
                w(f"- ⟨pattern⟩ `{p['glob']}`: {p['instance']}\n")
            w("\n")
    if ctx is not None:  # 2.0: sections from the roster_sections hooks, after the 1.x ones (contract 1.4, 8.3)
        for _, sections in registry.collect("roster_sections", ctx):
            for title, body in sections or []:
                if not out.getvalue().endswith("\n\n"):
                    w("\n")
                w(f"## {title}\n\n{str(body).rstrip()}\n\n")
    return out.getvalue()
