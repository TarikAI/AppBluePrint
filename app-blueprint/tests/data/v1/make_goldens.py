"""Golden STRUCTURE.md and ROSTER.md from tool 1.3.0, for the W0 rule (contract 1.5).

    python app-blueprint/tests/data/v1/make_goldens.py            # regenerate from the frozen 1.3.0 copy

Writes views.json next to this file: the full STRUCTURE.md and ROSTER.md text for each case of example_cases().
The fuzz corpus has no stored goldens: test_package.py renders every fuzz plan with this frozen copy and with the
current tool side by side and compares them.

Only ever regenerate from the frozen copy (blueprint-1.3.0.py): the goldens say what 1.3.0 produced.
test_package.py renders the same cases with the current tool and compares (example_cases and render are shared).
Inputs are kept as JSON strings so line-ending conversion on checkout cannot change them.
"""
import importlib.util
import json
import shutil
import sys
import tempfile
from pathlib import Path
from unittest import mock

HERE = Path(__file__).resolve().parent
TESTS = HERE.parents[1]
SKILL = TESTS.parent
FROZEN = HERE / "blueprint-1.3.0.py"
EXAMPLE = SKILL / "references" / "example-blueprint.json"
SNAG_DESK = HERE / "snag-desk-input.json"   # examples/snag-desk as 1.3.0 generated it: plan, state, files
VIEWS = HERE / "views.json"


def load_tool(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def fuzz_corpus():
    """(mutation_paths, apply, VALUES, MIGRATION, MAIN_RS) from test_plan_fuzz, so the corpus is the fuzz corpus."""
    if str(TESTS) not in sys.path:
        sys.path.insert(0, str(TESTS))
    import test_plan_fuzz as tf
    return tf


def write_tree(root, files):
    for rel, text in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(text.encode("utf-8"))


def render(bp, root, scan):
    """STRUCTURE.md and ROSTER.md for the plan in root, the way the fuzz test and sync reach them."""
    plan = bp.load_plan(root)
    bp.validate_plan(plan)
    state = bp.load_state(root)
    if scan and (plan["stores"] or plan["resources"]):
        state["data"] = bp.scan_data(root, plan, state, bp.repo_files(root, plan))
    comp = bp.compute(root, plan, state)
    return bp.render_structure(plan, state, comp), bp.render_roster(plan, state, comp)


def example_cases(bp):
    """Full views for: the example plan on an empty project; the example plan on the fuzz test's disk with the data
    scan; and examples/snag-desk (plan, state and files) as generated by 1.3.0."""
    tf = fuzz_corpus()
    base = json.loads(EXAMPLE.read_text(encoding="utf-8"))
    out = {}
    with mock.patch.object(bp.subprocess, "run", side_effect=OSError("no git in the golden test")):
        for case in ("example-empty", "example-fuzz-disk", "snag-desk"):
            root = Path(tempfile.mkdtemp(prefix="bp-golden-"))
            try:
                (root / ".blueprint").mkdir()
                if case == "snag-desk":
                    inp = json.loads(SNAG_DESK.read_text(encoding="utf-8"))
                    write_tree(root, inp["files"])
                    (root / ".blueprint" / "blueprint.json").write_text(inp["blueprint"], encoding="utf-8")
                    (root / ".blueprint" / "state.json").write_text(inp["state"], encoding="utf-8")
                    s, r = render(bp, root, scan=False)
                else:
                    if case == "example-fuzz-disk":
                        write_tree(root, {f["path"]: tf.MIGRATION if f["path"].endswith(".sql") else tf.MAIN_RS
                                          for f in base["files"]})
                        write_tree(root, {"extra/loose.txt": "x\n"})
                    (root / ".blueprint" / "blueprint.json").write_text(json.dumps(base), encoding="utf-8")
                    s, r = render(bp, root, scan=case == "example-fuzz-disk")
                out[case] = {"STRUCTURE.md": s, "ROSTER.md": r}
            finally:
                shutil.rmtree(root, ignore_errors=True)
    return out


def freeze_snag_desk(example_dir):
    """Record examples/snag-desk (1.3.0 output) as an input: plan and state text and every file outside .blueprint/."""
    import hashlib
    bpd = example_dir / ".blueprint"
    shas = {k: (v.get("verified") or {}).get("sha")
            for k, v in json.loads((bpd / "state.json").read_text(encoding="utf-8"))["files"].items()}
    files = {}
    for p in sorted(example_dir.rglob("*")):
        rel = p.relative_to(example_dir).as_posix()
        if p.is_file() and not rel.startswith(".blueprint/"):
            text = p.read_bytes().decode("utf-8")
            crlf = text.replace("\r\n", "\n").replace("\n", "\r\n")
            # make_example ran on Windows, so verified shas were taken of CRLF files: keep the form that matches
            if shas.get(rel) and hashlib.sha1(crlf.encode("utf-8")).hexdigest() == shas[rel]:
                text = crlf
            files[rel] = text
    data = {"source": "examples/snag-desk as generated by app-blueprint 1.3.0",
            "blueprint": (bpd / "blueprint.json").read_bytes().decode("utf-8"),
            "state": (bpd / "state.json").read_bytes().decode("utf-8"), "files": files}
    SNAG_DESK.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    if "--freeze-example" in argv:  # once, from the 1.3.0 example
        freeze_snag_desk(SKILL.parent / "examples" / "snag-desk")
    bp = load_tool(FROZEN, "blueprint_frozen_1_3_0")
    if bp.TOOL_VERSION != "1.3.0":
        raise SystemExit(f"{FROZEN} is not tool 1.3.0")
    views = example_cases(bp)
    VIEWS.write_text(json.dumps(views, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {VIEWS.name} ({len(views)} cases)")


if __name__ == "__main__":
    main()
