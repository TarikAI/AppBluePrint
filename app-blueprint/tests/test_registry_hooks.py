            self.assertEqual(self.run_("render")[0], 0)
            for case in ("read-only temp", "open temp", "read-only linked view"):
                with self.subTest(case=case):
                    victim = self.outside_file(case.replace(" ", "-") + ".md")
                    before = victim.read_bytes()
