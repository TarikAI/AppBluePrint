"""State integrity when several agents run the tool at once, and clean errors for a state.json that cannot be used.

Every read-modify-write of .blueprint/state.json goes through one locked helper (core.update_state, core.state_lock):
an OS advisory lock on .blueprint/state.lock, state re-read inside the lock, atomic writes through a temp file unique
to the process, and log.jsonl lines appended inside the same lock. The races below run real processes through the CLI
(the project's own copy of the tool, made by init from this skill), so a lost update, a crash on a shared temp name or
a torn log line shows up as a failure. state.json is padded with unplanned entries so each read-modify-write takes
long enough for overlapping writers to collide without the lock.

Environment: BP_RACE_N (processes per race, default 24), BP_RACE_ROUNDS (rounds of the claim race, default 2).
"""
