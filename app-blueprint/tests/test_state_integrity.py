    def gitignore(self):
        return (self.p.bp / ".gitignore")

    def fresh_lock(self):
        lock = self.p.bp / "state.lock"
        if lock.exists():
            lock.unlink()

    def test_init_writes_the_gitignore(self):
        lines = self.gitignore().read_text(encoding="utf-8").splitlines()
        self.assertIn("state.lock", lines)
        self.assertIn("*.tmp", lines)

    def test_first_lock_creates_a_missing_gitignore(self):
        self.gitignore().unlink()
        self.fresh_lock()
        self.assertEqual(self.p.run("mark", "src/f1.txt", "built", "--by", "o1")[0], 0)
        self.assertEqual(self.gitignore().read_text(encoding="utf-8").splitlines(), ["state.lock", "*.tmp"])

    def test_user_lines_are_kept_and_missing_lines_appended(self):
        self.gitignore().write_bytes(b"# mine\r\nnotes/\r\nstate.lock")
        self.fresh_lock()
        self.assertEqual(self.p.run("claim", "src/f1.txt", "--by", "o1")[0], 0)
        self.assertEqual(self.gitignore().read_bytes(), b"# mine\r\nnotes/\r\nstate.lock\n*.tmp\n")

    def test_a_complete_gitignore_is_not_touched(self):
        self.gitignore().write_bytes(b"*.tmp\nfoo\nstate.lock\n")
        before = self.gitignore().stat().st_mtime_ns
        self.fresh_lock()
        self.assertEqual(self.p.run("claim", "src/f1.txt", "--by", "o1")[0], 0)
        self.assertEqual(self.gitignore().read_bytes(), b"*.tmp\nfoo\nstate.lock\n")
        self.assertEqual(self.gitignore().stat().st_mtime_ns, before)

    def test_refresh_tool_adds_the_lines(self):
        self.gitignore().write_text("mine\n", encoding="utf-8")
        r = S.run_script(S.LAUNCHER, ["init", "--refresh-tool", "--root", self.p.root], cwd=self.p.root)
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertEqual(self.gitignore().read_text(encoding="utf-8").splitlines(), ["mine", "state.lock", "*.tmp"])

