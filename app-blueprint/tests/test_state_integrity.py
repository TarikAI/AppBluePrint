"""State integrity when several agents run the tool at once, and clean errors for a state.json that cannot be used.

Every read-modify-write of .blueprint/state.json goes through one locked helper (core.update_state, core.state_lock):
an OS advisory lock on .blueprint/state.lock, state re-read inside the lock, atomic writes through a temp file unique
to the process, and log.jsonl lines appended inside the same lock. The races below run real processes through the CLI
(the project's own copy of the tool, made by init from this skill), so a lost update, a crash on a shared temp name or
a torn log line shows up as a failure. state.json is padded with unplanned entries so each read-modify-write takes
long enough for overlapping writers to collide without the lock.

Environment: BP_RACE_N (processes per race, default 24), BP_RACE_ROUNDS (rounds of the claim race, default 2).
"""
import errno
import io
import json
import os
import shlex
import shutil
import stat
import subprocess
import sys
import tempfile
import time
import unittest
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path
from unittest import mock

import support as S
from bp import core, registry

N = int(os.environ.get("BP_RACE_N", "24"))
ROUNDS = int(os.environ.get("BP_RACE_ROUNDS", "2"))
PAD = 8000          # unplanned entries in state.json: they make each read-modify-write slow enough to collide
WAIT = 600          # seconds a whole race may take before it counts as a hang
LOCK_WAIT = "300"   # BLUEPRINT_LOCK_TIMEOUT for the races: a loaded machine must not turn waiting into state-busy
HEADER = "<!-- Generated by blueprint.py render. Do not edit. -->"
STUB_VIEW = (
    "import os\n\n\n"
    "def views(ctx):\n"
    "    n = os.environ.get('BP_TEST_VIEW')\n"
    "    return {'RACE-%s.md' % n: '# race\\n" + HEADER + "\\n'} if n else {}\n")


def shell_cmd(*parts):
    """A command line for the platform's shell (verify commands run with shell=True)."""
    if os.name == "nt":
        return subprocess.list2cmdline(list(parts))
    return " ".join(shlex.quote(p) for p in parts)


def make_plan(n, verify=None, tasks=False):
    files = []
    for i in range(n):
        f = {"path": f"src/f{i}.txt", "action": "create", "module": "core", "phase": "P1", "purpose": f"file {i}",
             "infrastructure": True}
        if verify is not None:
            f["verify"] = verify(i)
        files.append(f)
    return {
        "version": 2, "app": {"name": "Race", "summary": "", "platforms": [], "preset": ""}, "stack": [],
        "approach": {"layout": "", "notes": ""},
        "modules": [{"id": "core", "path": "src", "purpose": "the files", "layer": "core"}],
        "phases": [{"id": "P1", "name": "One", "goal": "g", "exit": ""}],
        "files": files, "patterns": [],
        "owners": [{"pattern": f"src/f{i}.txt", "owner": f"o{i}"} for i in range(n)],
        "roster": [{"id": f"o{i}", "kind": "agent", "role": "builder"} for i in range(n)],
        "decisions": [], "ignore": [], "milestones": [], "features": [],
        "tasks": [{"id": f"T-c{i}", "title": f"task {i}", "owner": f"o{i}"} for i in range(n)] if tasks else [],
        "unknowns": [],
    }


class Project:
    """A project made by `init` from this skill, so commands run through its own copy of the tool."""

    def __init__(self, n=N, verify=None, tasks=False, pad=PAD, stub_view=False):
        self._tmp = tempfile.TemporaryDirectory(prefix="bp-state-")
        self.root = Path(self._tmp.name) / "p"
        self.root.mkdir()
        self.bp = self.root / ".blueprint"
        r = S.run_script(S.LAUNCHER, ["init", "--name", "Race", "--root", self.root], cwd=self.root)
        if r.returncode != 0:
            raise AssertionError(f"init failed: {r.stdout}{r.stderr}")
        self.tool = self.bp / "bin" / "blueprint.py"
        (self.bp / "blueprint.json").write_text(json.dumps(make_plan(n, verify, tasks), indent=2) + "\n",
                                                encoding="utf-8")
        (self.root / "src").mkdir()
        for i in range(n):
            (self.root / "src" / f"f{i}.txt").write_text(f"file {i}\n", encoding="utf-8")
        if pad:
            state = json.loads((self.bp / "state.json").read_text(encoding="utf-8"))
            state["files"].update({f"pad/x{i}.txt": {"state": "built", "by": "o0", "at": "2026-01-01T00:00:00Z",
                                                     "note": "padding " * 4} for i in range(pad)})
            (self.bp / "state.json").write_text(json.dumps(state, indent=2) + "\n", encoding="utf-8")
        if stub_view:
            (self.bp / "bin" / "bp" / "views" / "features_md.py").write_text(STUB_VIEW, encoding="utf-8")
        self.pad = pad

    def close(self):
        for p in [self.bp, self.bp / "state.json"]:
            try:
                os.chmod(p, stat.S_IRWXU) if p.is_dir() else os.chmod(p, stat.S_IREAD | stat.S_IWRITE)
            except OSError:
                pass
        self._tmp.cleanup()

    def env(self, **extra):
        return S.tool_env(BLUEPRINT_LOCK_TIMEOUT=LOCK_WAIT, **extra)

    def argv(self, args):
        return [S.PY, str(self.tool)] + [str(a) for a in args] + ["--root", str(self.root)]

    def run(self, *args, env=None, stdin=None, timeout=300):
        r = subprocess.run(self.argv(args), cwd=str(self.root), capture_output=True, text=True, encoding="utf-8",
                           errors="replace", env=env or self.env(), input=stdin, timeout=timeout)
        return r.returncode, r.stdout, r.stderr

    def start(self, args, env=None):
        return subprocess.Popen(self.argv(args), cwd=str(self.root), stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                stdin=subprocess.DEVNULL, env=env or self.env())

    def state(self):
        return json.loads((self.bp / "state.json").read_text(encoding="utf-8"))

    def log_lines(self):
        path = self.bp / "log.jsonl"
        return path.read_text(encoding="utf-8").splitlines() if path.exists() else []

    def tmp_files(self):
        return sorted(p.name for p in self.bp.iterdir() if p.name.endswith(".tmp"))


def finish(procs, test):
    """Wait for every process; a hang fails the test fast instead of blocking the suite. Returns
    [(returncode, stdout, stderr, finished_at)] in the order given."""
    deadline = time.monotonic() + WAIT
    pending = dict(enumerate(procs))
    done = {}
    while pending:
        for i, p in list(pending.items()):
            if p.poll() is not None:
                out, err = p.communicate()
                done[i] = (p.returncode, out.decode("utf-8", "replace"), err.decode("utf-8", "replace"), time.monotonic())
                del pending[i]
        if pending and time.monotonic() > deadline:
            for p in pending.values():
                p.kill()
            test.fail(f"{len(pending)} process(es) still running after {WAIT}s: a deadlock or a hang")
        time.sleep(0.02)
    return [done[i] for i in range(len(procs))]


class IntegrityChecks:
    """Assertions shared by the races: every command succeeded, state.json is valid with its padding intact, the
    log gained exactly the expected events as whole lines, and no temp file was left behind."""

    def assert_all_ok(self, results, what):
        bad = [(code, err.strip()[-400:]) for code, _, err, _ in results if code != 0]
        self.assertEqual(bad, [], f"{what}: every command must exit 0")

    def assert_integrity(self, p, log_before, expected_events):
        state = p.state()  # valid JSON, or this raises
        self.assertIsInstance(state, dict)
        self.assertEqual(state.get("stateVersion"), 2)
        pads = [k for k in state["files"] if k.startswith("pad/")]
        self.assertEqual(len(pads), p.pad, "another writer's entries were lost")
        new = p.log_lines()[len(log_before):]
        events = []
        for line in new:
            rec = json.loads(line)  # a torn or merged line fails here
            self.assertIsInstance(rec, dict)
            events.append(rec.get("event"))
        self.assertEqual(sorted(events), sorted(expected_events), "one intact log line per event")
        self.assertEqual(p.tmp_files(), [], "no temp file may be left behind")
        return state


class ParallelWriters(IntegrityChecks, unittest.TestCase):
    """Real processes through the CLI: N writers at once must all land."""

    def test_parallel_claim_mark_verify_on_different_files(self):
        p = Project(verify=lambda i: shell_cmd(S.PY, "-c", "pass", str(i)))
        self.addCleanup(p.close)
        for rnd in range(ROUNDS):
            if rnd:  # back to planned for the next round
                res = finish([p.start(["mark", f"src/f{i}.txt", "planned", "--by", f"o{i}"]) for i in range(N)], self)
                self.assert_all_ok(res, "mark planned")
            before = p.log_lines()
            res = finish([p.start(["claim", f"src/f{i}.txt", "--by", f"o{i}", "--note", f"r{rnd}"]) for i in range(N)], self)
            self.assert_all_ok(res, "claim")
            state = self.assert_integrity(p, before, ["claimed"] * N)
            missing = [i for i in range(N) if state["files"].get(f"src/f{i}.txt", {}).get("state") != "claimed"]
            self.assertEqual(missing, [], f"round {rnd}: claims lost")
        before = p.log_lines()
        res = finish([p.start(["mark", f"src/f{i}.txt", "built", "--by", f"o{i}"]) for i in range(N)], self)
        self.assert_all_ok(res, "mark built")
        state = self.assert_integrity(p, before, ["built"] * N)
        self.assertEqual([i for i in range(N) if state["files"][f"src/f{i}.txt"].get("state") != "built"], [])
        before = p.log_lines()
        res = finish([p.start(["verify", "--run", "--owner", f"o{i}"]) for i in range(N)], self)
        self.assert_all_ok(res, "verify --run")
        state = self.assert_integrity(p, before, ["verify"] * N)
        unproven = [i for i in range(N) if not (state["files"][f"src/f{i}.txt"].get("verified") or {}).get("ok")]
        self.assertEqual(unproven, [], "proofs lost")
        code, out, err = p.run("status", "--json")
        self.assertEqual(code, 0, err)
        rows = {r["path"]: r["status"] for r in json.loads(out)["rows"]}
        self.assertEqual({rows[f"src/f{i}.txt"] for i in range(N)}, {"verified"})

    def test_parallel_marks_on_the_same_file(self):
        p = Project()
        self.addCleanup(p.close)
        before = p.log_lines()
        res = finish([p.start(["mark", "src/f0.txt", "blocked", "--by", "o0", "--note", f"n{i}"]) for i in range(N)], self)
        self.assert_all_ok(res, "mark blocked")
        state = self.assert_integrity(p, before, ["blocked"] * N)
        rec = state["files"]["src/f0.txt"]
        self.assertEqual(rec["state"], "blocked")
        self.assertIn(rec["note"], {f"n{i}" for i in range(N)})
        notes = sorted(json.loads(line)["note"] for line in p.log_lines()[len(before):])
        self.assertEqual(notes, sorted(f"n{i}" for i in range(N)))

    @unittest.skipUnless(registry.exists("roadmap"), "the task command arrives with the roadmap module")
    def test_parallel_task_on_different_tasks(self):
        p = Project(tasks=True)
        self.addCleanup(p.close)
        before = p.log_lines()
        res = finish([p.start(["task", f"T-c{i}", "doing", "--by", f"o{i}"]) for i in range(N)], self)
        self.assert_all_ok(res, "task")
        state = self.assert_integrity(p, before, ["task"] * N)
        self.assertEqual([i for i in range(N) if (state.get("tasks") or {}).get(f"T-c{i}", {}).get("status") != "doing"],
                         [], "task statuses lost")

    def test_sync_racing_mark(self):
        p = Project()
        self.addCleanup(p.close)
        before = p.log_lines()
        syncs = 4
        procs = []
        for i in range(N):
            if i % (N // syncs) == 0:
                procs.append(p.start(["sync", "--quiet"]))
            procs.append(p.start(["mark", f"src/f{i}.txt", "built", "--by", f"o{i}"]))
        res = finish(procs, self)
        self.assert_all_ok(res, "sync and mark")
        n_sync = sum(1 for x in procs if "sync" in x.args)
        state = self.assert_integrity(p, before, ["built"] * N + ["sync"] * n_sync)
        self.assertEqual([i for i in range(N) if state["files"][f"src/f{i}.txt"].get("state") != "built"], [])
        self.assertTrue(state.get("syncedAt"))

    def test_render_racing_claim(self):
        p = Project(stub_view=True)
        self.addCleanup(p.close)
        before = p.log_lines()
        procs = []
        for i in range(N):
            procs.append(p.start(["claim", f"src/f{i}.txt", "--by", f"o{i}"]))
            if i % 3 == 0:
                procs.append(p.start(["render", "--force"], env=p.env(BP_TEST_VIEW=str(i))))
        res = finish(procs, self)
        self.assert_all_ok(res, "render and claim")
        state = self.assert_integrity(p, before, ["claimed"] * N)
        self.assertEqual([i for i in range(N) if state["files"][f"src/f{i}.txt"].get("state") != "claimed"], [])
        views = state.get("generatedViews")
        self.assertIsInstance(views, list)
        self.assertEqual(len(views), 1, "the last render's exact list")
        self.assertTrue((p.bp / views[0]).exists())

    def test_verify_with_a_slow_check_racing_mark(self):
        n = max(4, N // 2)
        marker = "check-started.txt"
        slow = shell_cmd(S.PY, "-c", f"import pathlib, time; pathlib.Path({marker!r}).touch(); time.sleep(12)")
        p = Project(n=n, verify=lambda i: slow if i == 0 else shell_cmd(S.PY, "-c", "pass"))
        self.addCleanup(p.close)
        before = p.log_lines()
        verify = p.start(["verify", "--run", "--owner", "o0"])
        deadline = time.monotonic() + 120
        while not (p.root / marker).exists():
            self.assertIsNone(verify.poll(), "verify ended before its check started")
            self.assertLess(time.monotonic(), deadline, "the slow check never started")
            time.sleep(0.05)
        marks = finish([p.start(["mark", f"src/f{i}.txt", "built", "--by", f"o{i}"]) for i in range(1, n)], self)
        self.assertIsNone(verify.poll(), "the marks must not wait for the check: the lock is never held across it")
        res = finish([verify], self)
        self.assert_all_ok(marks + res, "verify and mark")
        state = self.assert_integrity(p, before, ["built"] * (n - 1) + ["verify"])
        self.assertTrue(state["files"]["src/f0.txt"]["verified"]["ok"])
        self.assertEqual([i for i in range(1, n) if state["files"][f"src/f{i}.txt"].get("state") != "built"], [])


HOLDER = (
    "import sys, time\n"
    "sys.path.insert(0, sys.argv[1])\n"
    "from pathlib import Path\n"
    "from bp import core\n"
    "lock = core.state_lock(Path(sys.argv[2]))\n"
    "lock.__enter__()\n"
    "print('locked', flush=True)\n"
    "time.sleep(float(sys.argv[3]))\n"
    "lock.__exit__(None, None, None)\n")


class TheLock(IntegrityChecks, unittest.TestCase):

    def setUp(self):
        self.p = Project(n=4, pad=0)
        self.addCleanup(self.p.close)

    def hold(self, seconds):
        proc = subprocess.Popen([S.PY, "-c", HOLDER, str(S.SCRIPTS), str(self.p.root), str(seconds)],
                                stdout=subprocess.PIPE, stderr=subprocess.PIPE, env=S.tool_env())
        self.addCleanup(lambda: proc.poll() is None and proc.kill())
        line = proc.stdout.readline().decode().strip()
        self.assertEqual(line, "locked", proc.stderr.read().decode() if proc.poll() is not None else "")
        return proc

    def test_held_by_another_process_waits_then_succeeds(self):
        holder = self.hold(3)
        t0 = time.monotonic()
        code, out, err = self.p.run("mark", "src/f1.txt", "built", "--by", "o1", env=self.p.env())
        self.assertEqual(code, 0, err)
        self.assertGreater(time.monotonic() - t0, 1.0, "it should have waited for the holder")
        holder.wait(timeout=60)
        self.assertEqual(self.p.state()["files"]["src/f1.txt"]["state"], "built")

    def test_held_past_the_timeout_is_state_busy(self):
        self.hold(120)
        before = self.p.state()
        code, out, err = self.p.run("mark", "src/f1.txt", "built", "--by", "o1",
                                    env=S.tool_env(BLUEPRINT_LOCK_TIMEOUT="1"))
        self.assertEqual(code, 1, err)
        self.assertIn("error: another blueprint command is writing .blueprint/state.json", err)
        self.assertIn("next: run the same command again:", err)
        self.assertIn("mark src/f1.txt built --by o1", err)
        self.assertEqual(self.p.state(), before)
        code, out, err = self.p.run("status", "--json", env=S.tool_env(BLUEPRINT_LOCK_TIMEOUT="1"))
        self.assertEqual(code, 0, "readers never wait for the lock")

    def test_state_busy_for_sync_and_the_log(self):
        self.hold(120)
        log_before = self.p.log_lines()
        code, out, err = self.p.run("sync", "--quiet", env=S.tool_env(BLUEPRINT_LOCK_TIMEOUT="0.5"))
        self.assertEqual(code, 1, err)
        self.assertIn("error: another blueprint command is writing .blueprint/state.json", err)
        code, out, err = self.p.run("contracts", "--write", env=S.tool_env(BLUEPRINT_LOCK_TIMEOUT="0.5"))
        self.assertEqual(code, 1, "a log line is appended inside the lock too")
        self.assertEqual(self.p.log_lines(), log_before)

    def test_killed_holder_leaves_the_project_usable(self):
        holder = self.hold(300)
        holder.kill()
        holder.wait(timeout=60)
        t0 = time.monotonic()
        code, out, err = self.p.run("mark", "src/f2.txt", "built", "--by", "o2", env=S.tool_env(BLUEPRINT_LOCK_TIMEOUT="5"))
        self.assertEqual(code, 0, err)
        self.assertLess(time.monotonic() - t0, 30)
        self.assertEqual(self.p.state()["files"]["src/f2.txt"]["state"], "built")

    def test_the_lock_is_never_nested(self):
        with core.state_lock(self.p.root):
            with self.assertRaises(RuntimeError):
                with core.state_lock(self.p.root):
                    pass
        with core.state_lock(self.p.root):  # released: can be taken again
            pass

    def test_a_file_system_without_locks_is_a_clean_error(self):
        from bp import cli
        err = io.StringIO()
        with mock.patch.object(core, "_try_lock", side_effect=OSError(errno.ENOLCK, "No locks available")), \
                redirect_stderr(err), redirect_stdout(io.StringIO()), \
                mock.patch.dict(os.environ, S.tool_env()):
            with self.assertRaises(SystemExit) as cm:
                cli.main(["mark", "src/f1.txt", "built", "--by", "o1", "--root", str(self.p.root)])
        self.assertEqual(cm.exception.code, 1)
        self.assertIn("error: ", err.getvalue())
        self.assertIn("lock", err.getvalue())
        self.assertNotIn("unexpected", err.getvalue())

    def test_lock_file_that_cannot_be_opened(self):
        """A lock that cannot be taken (here state.lock is a folder) fails writing commands cleanly; read-only commands
        still answer."""
        lock = self.p.bp / "state.lock"
        if lock.exists():
            lock.unlink()
        lock.mkdir()
        code, out, err = self.p.run("render", "--force")
        self.assertEqual(code, 1, err)
        self.assertIn("state.lock", err)
        for args in (["mark", "src/f1.txt", "built", "--by", "o1"], ["sync", "--quiet"], ["claim", "src/f1.txt", "--by", "o1"]):
            code, out, err = self.p.run(*args)
            self.assertEqual(code, 1, (args, err))
            self.assertIn("error: ", err)
            self.assertNotEqual(code, 70)
        for args in (["status"], ["status", "--json"], ["validate"], ["render", "--check"], ["export", "json"]):
            code, out, err = self.p.run(*args)
            self.assertIn(code, (0, 1), (args, err))
            self.assertNotIn("error: ", err, args)

    @unittest.skipIf(os.name == "nt" or (hasattr(os, "geteuid") and os.geteuid() == 0),
                     "a read-only folder needs POSIX permissions and a non-root user")
    def test_read_only_project_folder(self):
        code, _, err = self.p.run("render", "--force")
        self.assertEqual(code, 0, err)
        (self.p.bp / "state.lock").unlink()
        os.chmod(self.p.bp, stat.S_IRUSR | stat.S_IXUSR)
        code, out, err = self.p.run("mark", "src/f1.txt", "built", "--by", "o1")
        self.assertEqual(code, 1, err)
        self.assertIn("error: ", err)
        for args in (["status"], ["validate"], ["render", "--check"], ["export", "json"]):
            code, out, err = self.p.run(*args)
            self.assertEqual(code, 0, (args, err))


class BrokenState(unittest.TestCase):
    """C2: a state.json that cannot be used is error bad-state (exit 1), never an incident, and is left as it is."""

    WRITERS = (["mark", "src/f1.txt", "built", "--by", "o1"], ["claim", "src/f1.txt", "--by", "o1"], ["sync", "--quiet"],
               ["render", "--force"])
    READERS = (["status"], ["render", "--check"], ["export", "json"], ["contracts"])

    def setUp(self):
        self.p = Project(n=3, pad=0)
        self.addCleanup(self.p.close)
        self.path = self.p.bp / "state.json"

    def put(self, content):
        self.path.write_bytes(content if isinstance(content, bytes) else content.encode("utf-8"))

    def assert_bad_state(self, args, words):
        before = self.path.read_bytes() if self.path.is_file() else None
        code, out, err = self.p.run(*args)
        self.assertEqual(code, 1, (args, out, err))
        self.assertIn("error: .blueprint/state.json " + words, err, args)
        self.assertIn("  next: ", err, args)
        if before is not None:
            self.assertEqual(self.path.read_bytes(), before, "a broken state is never reset or rewritten")

    def assert_json_envelope(self, words):
        code, out, err = self.p.run("status", "--json")
        self.assertEqual(code, 1, err)
        env = json.loads(out)
        self.assertEqual(env["ok"], False)
        self.assertEqual(env["command"], "status")
        self.assertEqual(env["error"]["code"], "bad-state")
        self.assertIn(words, env["error"]["message"])
        self.assertTrue(env["error"]["next"])
        self.assertEqual(env["error"]["entry"], ".blueprint/state.json")

    def check_all(self, words):
        for args in self.WRITERS + self.READERS:
            self.assert_bad_state(list(args), words)
        self.assert_json_envelope(words)
        self.assert_guard_unchanged()

    def assert_guard_unchanged(self):
        """guard and hook pre never read state: a broken state neither blocks nor allows more than before."""
        self.assertEqual(self.p.run("guard", "src/f1.txt", "--by", "o1")[0], 0)
        self.assertEqual(self.p.run("guard", "src/unplanned.txt", "--by", "o1")[0], 2)
        payload = json.dumps({"tool_input": {"file_path": str(self.p.root / "src" / "unplanned.txt")},
                              "cwd": str(self.p.root)})
        r = subprocess.run([S.PY, str(self.p.tool), "hook", "pre"], cwd=str(self.p.root), input=payload,
                           capture_output=True, text=True, encoding="utf-8", env=S.tool_env(), timeout=300)
        self.assertEqual(r.returncode, 2, r.stderr)

    def test_not_json(self):
        self.put("{bad")
        self.check_all("is not valid JSON")

    def test_not_utf8(self):
        self.put(b"\xff\xfe{")
        self.check_all("is not UTF-8 text")

    def test_a_list(self):
        self.put("[]")
        self.check_all("must be a JSON object (got list)")

    def test_null(self):
        self.put("null")
        self.check_all("must be a JSON object (got null)")

