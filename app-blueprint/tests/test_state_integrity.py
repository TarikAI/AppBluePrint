N = int(os.environ.get("BP_RACE_N", "24"))
ROUNDS = int(os.environ.get("BP_RACE_ROUNDS", "2"))
PAD = 8000          # unplanned entries in state.json: they make each read-modify-write slow enough to collide
WAIT = 600          # seconds a whole race may take before it counts as a hang
LOCK_WAIT = "300"   # BLUEPRINT_LOCK_TIMEOUT for the races: a loaded machine must not turn waiting into state-busy
HEADER = "<!-- Generated by blueprint.py render. Do not edit. -->"
STUB_VIEW = (
    "import os\n\n\n"
    "def views(ctx):\n"
    "    n = os.environ.get('BP_TEST_VIEW')\n"
    "    return {'RACE-%s.md' % n: '# race\\n" + HEADER + "\\n'} if n else {}\n")


def shell_cmd(*parts):
    """A command line for the platform's shell (verify commands run with shell=True)."""
    if os.name == "nt":
        return subprocess.list2cmdline(list(parts))
    return " ".join(shlex.quote(p) for p in parts)


def make_plan(n, verify=None, tasks=False):
    files = []
    for i in range(n):
        f = {"path": f"src/f{i}.txt", "action": "create", "module": "core", "phase": "P1", "purpose": f"file {i}",
             "infrastructure": True}
        if verify is not None:
            f["verify"] = verify(i)
        files.append(f)
    return {
        "version": 2, "app": {"name": "Race", "summary": "", "platforms": [], "preset": ""}, "stack": [],
        "approach": {"layout": "", "notes": ""},
        "modules": [{"id": "core", "path": "src", "purpose": "the files", "layer": "core",
                     "verify": shell_cmd(S.PY, "-c", "pass")}],
        "phases": [{"id": "P1", "name": "One", "goal": "g", "exit": ""}],
        "files": files, "patterns": [],
        "owners": [{"pattern": f"src/f{i}.txt", "owner": f"o{i}"} for i in range(n)],
        "roster": [{"id": f"o{i}", "kind": "agent", "role": "builder"} for i in range(n)],
        "decisions": [], "ignore": [], "milestones": [], "features": [],
        "tasks": [{"id": f"T-c{i}", "title": f"task {i}", "owner": f"o{i}"} for i in range(n)] if tasks else [],
        "unknowns": [],
    }


class Project:
    """A project made by `init` from this skill, so commands run through its own copy of the tool."""

    def __init__(self, n=N, verify=None, tasks=False, pad=PAD, stub_view=False):
        self._tmp = tempfile.TemporaryDirectory(prefix="bp-state-")
        self.root = Path(self._tmp.name) / "p"
        self.root.mkdir()
        self.bp = self.root / ".blueprint"
        r = S.run_script(S.LAUNCHER, ["init", "--name", "Race", "--root", self.root], cwd=self.root)
        if r.returncode != 0:
            raise AssertionError(f"init failed: {r.stdout}{r.stderr}")
        self.tool = self.bp / "bin" / "blueprint.py"
        (self.bp / "blueprint.json").write_text(json.dumps(make_plan(n, verify, tasks), indent=2) + "\n",
                                                encoding="utf-8")
        (self.root / "src").mkdir()
        for i in range(n):
            (self.root / "src" / f"f{i}.txt").write_text(f"file {i}\n", encoding="utf-8")
        if pad:
            state = json.loads((self.bp / "state.json").read_text(encoding="utf-8"))
            state["files"].update({f"pad/x{i}.txt": {"state": "built", "by": "o0", "at": "2026-01-01T00:00:00Z",
                                                     "note": "padding " * 4} for i in range(pad)})
            (self.bp / "state.json").write_text(json.dumps(state, indent=2) + "\n", encoding="utf-8")
        if stub_view:
            (self.bp / "bin" / "bp" / "views" / "features_md.py").write_text(STUB_VIEW, encoding="utf-8")
        self.pad = pad

    def close(self):
        for p in [self.bp, self.bp / "state.json"]:
            try:
                os.chmod(p, stat.S_IRWXU) if p.is_dir() else os.chmod(p, stat.S_IREAD | stat.S_IWRITE)
            except OSError:
                pass
        self._tmp.cleanup()

    def env(self, **extra):
        return S.tool_env(BLUEPRINT_LOCK_TIMEOUT=LOCK_WAIT, **extra)

    def argv(self, args):
        return [S.PY, str(self.tool)] + [str(a) for a in args] + ["--root", str(self.root)]

    def run(self, *args, env=None, stdin=None, timeout=300):
        r = subprocess.run(self.argv(args), cwd=str(self.root), capture_output=True, text=True, encoding="utf-8",
                           errors="replace", env=env or self.env(), input=stdin, timeout=timeout)
        return r.returncode, r.stdout, r.stderr

    def start(self, args, env=None):
        return subprocess.Popen(self.argv(args), cwd=str(self.root), stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                stdin=subprocess.DEVNULL, env=env or self.env())

    def state(self):
        return json.loads((self.bp / "state.json").read_text(encoding="utf-8"))

    def log_lines(self):
        path = self.bp / "log.jsonl"
        return path.read_text(encoding="utf-8").splitlines() if path.exists() else []

    def tmp_files(self):
        return sorted(p.name for p in self.bp.iterdir() if p.name.endswith(".tmp"))


def finish(procs, test):
    """Wait for every process; a hang fails the test fast instead of blocking the suite. Returns
    [(returncode, stdout, stderr, finished_at)] in the order given."""
    deadline = time.monotonic() + WAIT
    pending = dict(enumerate(procs))
    done = {}
    while pending:
        for i, p in list(pending.items()):
            if p.poll() is not None:
                out, err = p.communicate()
                done[i] = (p.returncode, out.decode("utf-8", "replace"), err.decode("utf-8", "replace"), time.monotonic())
                del pending[i]
        if pending and time.monotonic() > deadline:
            for p in pending.values():
                p.kill()
            test.fail(f"{len(pending)} process(es) still running after {WAIT}s: a deadlock or a hang")
        time.sleep(0.02)
    return [done[i] for i in range(len(procs))]


class IntegrityChecks:
    """Assertions shared by the races: every command succeeded, state.json is valid with its padding intact, the
    log gained exactly the expected events as whole lines, and no temp file was left behind."""

    def assert_all_ok(self, results, what):
        bad = [(code, err.strip()[-400:]) for code, _, err, _ in results if code != 0]
        self.assertEqual(bad, [], f"{what}: every command must exit 0")

    def assert_integrity(self, p, log_before, expected_events):
        state = p.state()  # valid JSON, or this raises
        self.assertIsInstance(state, dict)
        self.assertEqual(state.get("stateVersion"), 2)
        pads = [k for k in state["files"] if k.startswith("pad/")]
        self.assertEqual(len(pads), p.pad, "another writer's entries were lost")
        new = p.log_lines()[len(log_before):]
        events = []
        for line in new:
            rec = json.loads(line)  # a torn or merged line fails here
            self.assertIsInstance(rec, dict)
            events.append(rec.get("event"))
        self.assertEqual(sorted(events), sorted(expected_events), "one intact log line per event")
        self.assertEqual(p.tmp_files(), [], "no temp file may be left behind")
        return state


class ParallelWriters(IntegrityChecks, unittest.TestCase):
    """Real processes through the CLI: N writers at once must all land."""

    def test_parallel_claim_mark_verify_on_different_files(self):
        p = Project(verify=lambda i: shell_cmd(S.PY, "-c", "pass", str(i)))
        self.addCleanup(p.close)
        for rnd in range(ROUNDS):
            if rnd:  # back to planned for the next round
                res = finish([p.start(["mark", f"src/f{i}.txt", "planned", "--by", f"o{i}"]) for i in range(N)], self)
                self.assert_all_ok(res, "mark planned")
            before = p.log_lines()
            res = finish([p.start(["claim", f"src/f{i}.txt", "--by", f"o{i}", "--note", f"r{rnd}"]) for i in range(N)], self)
            self.assert_all_ok(res, "claim")
            state = self.assert_integrity(p, before, ["claimed"] * N)
            missing = [i for i in range(N) if state["files"].get(f"src/f{i}.txt", {}).get("state") != "claimed"]
            self.assertEqual(missing, [], f"round {rnd}: claims lost")
        before = p.log_lines()
        res = finish([p.start(["mark", f"src/f{i}.txt", "built", "--by", f"o{i}"]) for i in range(N)], self)
        self.assert_all_ok(res, "mark built")
        state = self.assert_integrity(p, before, ["built"] * N)
        self.assertEqual([i for i in range(N) if state["files"][f"src/f{i}.txt"].get("state") != "built"], [])
        before = p.log_lines()
        res = finish([p.start(["verify", "--run", "--owner", f"o{i}"]) for i in range(N)], self)
        self.assert_all_ok(res, "verify --run")
        state = self.assert_integrity(p, before, ["verify"] * N)
        unproven = [i for i in range(N) if not (state["files"][f"src/f{i}.txt"].get("verified") or {}).get("ok")]
        self.assertEqual(unproven, [], "proofs lost")
        code, out, err = p.run("status", "--json")
        self.assertEqual(code, 0, err)
        rows = {r["path"]: r["status"] for r in json.loads(out)["rows"]}
        self.assertEqual({rows[f"src/f{i}.txt"] for i in range(N)}, {"verified"})

    def test_parallel_marks_on_the_same_file(self):
        p = Project()
        self.addCleanup(p.close)
        before = p.log_lines()
        res = finish([p.start(["mark", "src/f0.txt", "blocked", "--by", "o0", "--note", f"n{i}"]) for i in range(N)], self)
        self.assert_all_ok(res, "mark blocked")
        state = self.assert_integrity(p, before, ["blocked"] * N)
        rec = state["files"]["src/f0.txt"]
        self.assertEqual(rec["state"], "blocked")
        self.assertIn(rec["note"], {f"n{i}" for i in range(N)})
        notes = sorted(json.loads(line)["note"] for line in p.log_lines()[len(before):])
        self.assertEqual(notes, sorted(f"n{i}" for i in range(N)))

    @unittest.skipUnless(registry.exists("roadmap"), "the task command arrives with the roadmap module")
    def test_parallel_task_on_different_tasks(self):
        p = Project(tasks=True)
        self.addCleanup(p.close)
