def render_roster(plan, state, comp):
    rows, pats = comp["rows"], comp["patterns"]
    out = io.StringIO()
    w = out.write
    w(f"# {plan['app'].get('name')}: roster\n\n<!-- Generated by blueprint.py render. Do not edit. -->\n\n")
    w("Ownership follows the rules below in order; **the last matching rule wins**, as in CODEOWNERS. "
      "Write only files you own. Run `python .blueprint/bin/blueprint.py owner <path>` when unsure.\n\n")
    w("## Who\n\n| Owner | Kind | Harness | Role | Files | Verified | Patterns |\n|---|---|---|---|---|---|---|\n")
    for r in plan["roster"]:
        mine = [x for x in rows if x["owner"] == r["id"]]
        w(f"| {r['id']} | {r.get('kind')} | {md_cell(r.get('harness'))} | {md_cell(r.get('role'))} | {len(mine)} | "
          f"{sum(1 for x in mine if x['status'] == 'verified')} | {sum(1 for p in pats if p['owner'] == r['id'])} |\n")
    w("\n## Owner rules (last match wins)\n\n| # | Pattern | Owner | Override | Wins |\n|---|---|---|---|---|\n")
    for i, rule in enumerate(plan["owners"]):
        wins = sum(1 for x in rows if x["rule"] == i) + sum(1 for p in pats if p["rule"] == i)
        w(f"| {i + 1} | `{md_cell(rule.get('pattern'))}` | {rule.get('owner')} | {'yes' if rule.get('override') else ''} | {wins} |\n")
    w("\n## Write lists by owner and phase\n\n")
    for r in plan["roster"]:
        mine = [x for x in rows if x["owner"] == r["id"]]
        mp = [p for p in pats if p["owner"] == r["id"]]
        if not mine and not mp:
            continue
        w(f"### {r['id']}\n\n")
        for ph in plan["phases"]:
            fs = [x for x in mine if x["phase"] == ph["id"]]
            ps = [p for p in mp if p["phase"] == ph["id"]]
            if not fs and not ps:
                continue
            w(f"**{ph['id']} {ph.get('name', '')}**\n\n")
            for x in fs:
                w(f"- {GLYPH[x['status']]} `{x['path']}`{' ★' if x['contract'] else ''}{'' if x['action'] == 'create' else ' (' + x['action'] + ')'}\n")
            for p in ps:
                w(f"- ⟨pattern⟩ `{p['glob']}`: {p['instance']}\n")
            w("\n")
    return out.getvalue()


