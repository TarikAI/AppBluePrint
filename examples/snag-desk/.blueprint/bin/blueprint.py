def _html_escape(s):
    return str(s).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def render_all(root, plan, state, quiet=False, check=False):
    comp = compute(root, plan, state)
    outputs = {"STRUCTURE.md": render_structure(plan, state, comp), "ROSTER.md": render_roster(plan, state, comp)}
    m = render_map(plan, state, comp)
    if m is not None:
        outputs["map.html"] = m
    stale = []
    for name, text in outputs.items():
        path = bp_dir(root) / name
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        elif write_text_if_changed(path, text) and not quiet:
            print(f"wrote .blueprint/{name}")
    if m is None and not quiet:
        print("map.template.html not found next to the script; map.html skipped. Run init --refresh-tool.")
    return stale


def cmd_render(args):
    root = find_root(args.root)
    plan = load_plan(root)
    errors, _ = validate_plan(plan)
    if errors and not args.force:
        die(f"The blueprint has {len(errors)} error(s); run validate first (or render --force for a draft view).")
    state = load_state(root)
    if args.check:
        stale = render_all(root, plan, state, check=True)
        if stale:
            print("Out of date: " + ", ".join(stale) + ". Run: blueprint.py render")
            sys.exit(1)
        print("Views are current.")
        return
    render_all(root, plan, state)


