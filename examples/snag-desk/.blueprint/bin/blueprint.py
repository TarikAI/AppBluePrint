# ----------------------------------------------------------------------------- paths and io

def find_root(arg_root):
    if arg_root:
        return Path(arg_root).resolve()
    if HERE.name == "bin" and HERE.parent.name == ".blueprint":
        return HERE.parent.parent
    cur = Path.cwd().resolve()
    for p in [cur] + list(cur.parents):
        if (p / ".blueprint" / "blueprint.json").exists():
            return p
    return cur


def bp_dir(root):
    return root / ".blueprint"


def now_iso():
    return _dt.datetime.now(_dt.timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def read_json(path, default=None):
    if not path.exists():
        return default
    with path.open(encoding="utf-8") as f:
        return json.load(f)


def write_json(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    os.replace(tmp, path)


def write_text_if_changed(path, text):
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old != text:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        return True
    return False


def append_log(root, event):
    event = dict(event)
    event.setdefault("at", now_iso())
    with (bp_dir(root) / "log.jsonl").open("a", encoding="utf-8") as f:
        f.write(json.dumps(event, ensure_ascii=False) + "\n")


def norm(p):
    p = str(p).replace("\\", "/").strip()
    while p.startswith("./"):
        p = p[2:]
    return p


def file_sha(path):
    h = hashlib.sha1()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def die(msg, code=1):
    print(msg, file=sys.stderr)
    sys.exit(code)


# ----------------------------------------------------------------------------- globs (CODEOWNERS-like)

_RX_CACHE = {}


def glob_rx(pattern):
    """CODEOWNERS / gitignore-style glob.

    `*` stays inside one folder, `**` crosses folders, `?` is one character.
    A pattern with a slash (other than a trailing one) is anchored to the repo root;
    one without, like `*.md`, matches at any depth. A pattern that names a folder
    also matches everything inside it.
    """
    if pattern in _RX_CACHE:
        return _RX_CACHE[pattern]
    p = pattern.strip()
    anchored = p.startswith("/") or "/" in p.rstrip("/")
    p = p.lstrip("/")
    if p.endswith("/"):
        p = p + "**"
    out, i = "", 0
    while i < len(p):
        c = p[i]
        if c == "*":
            if p[i:i + 3] == "**/":
                out += "(?:.*/)?"
                i += 3
                continue
            if p[i:i + 2] == "**":
                out += ".*"
                i += 2
                continue
            out += "[^/]*"
        elif c == "?":
            out += "[^/]"
        else:
            out += re.escape(c)
        i += 1
    rx = re.compile(("^" if anchored else "^(?:.*/)?") + out + "(?:/.*)?$")
    _RX_CACHE[pattern] = rx
    return rx


def glob_match(pattern, path):
    return bool(glob_rx(pattern).match(norm(path)))


def pattern_instance_rx(glob):
    """A repeated-file pattern's glob, anchored, used to find its instances on disk."""
    p = norm(glob).lstrip("/")
    out, i = "", 0
    while i < len(p):
        c = p[i]
        if c == "*":
            if p[i:i + 3] == "**/":
                out += "(?:.*/)?"
                i += 3
                continue
            if p[i:i + 2] == "**":
                out += ".*"
                i += 2
                continue
            out += "[^/]*"
        elif c == "?":
            out += "[^/]"
        else:
            out += re.escape(c)
        i += 1
    return re.compile("^" + out + "$")


# ----------------------------------------------------------------------------- loading

def load_plan(root):
    path = bp_dir(root) / "blueprint.json"
    if not path.exists():
        die(f"No blueprint at {path}. Run: blueprint.py init --name \"App name\"")
    try:
        plan = read_json(path)
    except json.JSONDecodeError as e:
        die(f"blueprint.json is not valid JSON: {e}")
    for key, default in (("stack", []), ("modules", []), ("phases", []), ("files", []),
                         ("patterns", []), ("owners", []), ("roster", []), ("decisions", []),
                         ("ignore", []), ("approach", {}), ("app", {})):
        plan.setdefault(key, default)
    for f in plan["files"]:
        f["path"] = norm(f.get("path", ""))
    return plan


def load_state(root):
    return read_json(bp_dir(root) / "state.json", {"files": {}, "patterns": {}, "unplanned": [],
                                                   "syncedAt": None, "head": None})


def save_state(root, state):
    write_json(bp_dir(root) / "state.json", state)


def owner_of(plan, path):
    """Return (owner, rule_index, all_matching_indexes) using last-match-wins."""
    matches = [i for i, r in enumerate(plan["owners"]) if glob_match(r.get("pattern", ""), path)]
    if not matches:
        return None, None, []
    i = matches[-1]
    return plan["owners"][i].get("owner"), i, matches


def phase_index(plan):
    return {p.get("id"): i for i, p in enumerate(plan["phases"])}


def module_index(plan):
    return {m.get("id"): m for m in plan["modules"]}


def item_verify(plan, item):
    if item.get("verify"):
        return item["verify"]
    mod = module_index(plan).get(item.get("module"))
    return (mod or {}).get("verify")


# ----------------------------------------------------------------------------- validate

def validate_plan(plan, team=None):
    errors, warnings = [], []
    E, W = errors.append, warnings.append

    if plan.get("version") != SCHEMA_VERSION:
        E(f"version must be {SCHEMA_VERSION}")
    if not (plan.get("app") or {}).get("name"):
        E("app.name is empty")

    def uniq(items, key, label):
        seen = set()
        for it in items:
            v = it.get(key)
            if not v:
                E(f"{label} without {key}: {json.dumps(it)[:80]}")
            elif v in seen:
                E(f"duplicate {label} {key}: {v}")
            seen.add(v)
        return seen

    mods = uniq(plan["modules"], "id", "module")
    phases = uniq(plan["phases"], "id", "phase")
    roster = uniq(plan["roster"], "id", "roster entry")
    uniq(plan["files"], "path", "file")
    uniq(plan["patterns"], "id", "pattern")
    pidx = phase_index(plan)
    if not plan["phases"]:
        E("no phases: phase 1 must be a walking skeleton")

    for s in plan["stack"]:
        for k in ("part", "choice", "docs", "verified"):
            if not s.get(k):
                E(f"stack entry {s.get('part') or s.get('choice') or '?'}: missing {k} (record the docs URL and the date you checked it)")

    for m in plan["modules"]:
        for d in m.get("dependsOn", []):
            if d not in mods:
                E(f"module {m.get('id')}: depends on unknown module {d}")
        if not m.get("purpose"):
            E(f"module {m.get('id')}: empty purpose")
    # module cycles
    graph = {m.get("id"): list(m.get("dependsOn", [])) for m in plan["modules"]}
    state = {}

    def visit(n, stack):
        state[n] = 1
        for d in graph.get(n, []):
            if state.get(d) == 1:
                E("module dependency cycle: " + " -> ".join(stack + [n, d]))
            elif not state.get(d):
                visit(d, stack + [n])
        state[n] = 2

    for n in graph:
        if not state.get(n):
            visit(n, [])

    for r in plan["roster"]:
        if r.get("kind") not in ROSTER_KINDS:
            E(f"roster {r.get('id')}: kind must be agent or human")

    planned_paths = {f["path"] for f in plan["files"]}
    pat_rx = [(p.get("id"), pattern_instance_rx(p.get("glob", ""))) for p in plan["patterns"] if p.get("glob")]

    def known_dep(d):
        d = norm(d)
        return d in planned_paths or any(rx.match(d) for _, rx in pat_rx) or d in {p.get("id") for p in plan["patterns"]}

    files_by_path = {f["path"]: f for f in plan["files"]}
    for f in plan["files"]:
        path = f["path"]
        if not path or path.startswith("/") or ".." in path.split("/") or re.match(r"^[A-Za-z]:", path):
            E(f"file {path!r}: use a repo-relative path")
        if f.get("action") not in ACTIONS:
            E(f"file {path}: action must be create, modify or delete")
        if f.get("module") not in mods:
            E(f"file {path}: unknown module {f.get('module')!r}")
        if f.get("phase") not in phases:
            E(f"file {path}: unknown phase {f.get('phase')!r}")
        if not f.get("purpose"):
            E(f"file {path}: empty purpose (one sentence: what this file is for)")
        if f.get("action") != "delete" and not item_verify(plan, f):
            E(f"file {path}: no verify command (set it on the file or its module)")
        for d in f.get("dependsOn", []):
            if not known_dep(d):
                E(f"file {path}: depends on {d}, which is not planned")
            dep = files_by_path.get(norm(d))
            if dep and dep.get("phase") in pidx and f.get("phase") in pidx and pidx[dep["phase"]] > pidx[f["phase"]]:
                E(f"file {path} ({f['phase']}) depends on {d} ({dep['phase']}), which lands in a later phase")

    for p in plan["patterns"]:
        pid = p.get("id")
        if not p.get("glob"):
            E(f"pattern {pid}: empty glob")
        if p.get("module") not in mods:
            E(f"pattern {pid}: unknown module {p.get('module')!r}")
        if p.get("phase") not in phases:
            E(f"pattern {pid}: unknown phase {p.get('phase')!r}")
        if not p.get("purpose") or not p.get("instance"):
            E(f"pattern {pid}: needs purpose and instance (what one instance contains)")
        if not item_verify(plan, p):
            E(f"pattern {pid}: no verify command (set it on the pattern or its module)")

    # produces / consumes
    produced = set()
    for f in plan["files"]:
        produced.update(f.get("produces", []))
    for f in plan["files"]:
        for c in f.get("consumes", []):
            if c not in produced:
                W(f"file {f['path']}: consumes {c!r}, which no planned file produces")

    # ownership
    rules = plan["owners"]
    for i, r in enumerate(rules):
        if not r.get("pattern") or not r.get("owner"):
            E(f"owner rule {i + 1}: needs pattern and owner")
        elif r["owner"] not in roster:
            E(f"owner rule {i + 1} ({r['pattern']}): owner {r['owner']!r} is not in the roster")
    wins = {i: 0 for i in range(len(rules))}
    hits = {i: 0 for i in range(len(rules))}
    items = [(f["path"], f["path"]) for f in plan["files"]] + [(p.get("glob", ""), "pattern " + str(p.get("id"))) for p in plan["patterns"]]
    # Which planned items each rule matches. A later rule whose matches all fall inside an earlier
    # rule's matches is a normal CODEOWNERS refinement (fallback first, specifics after). A later rule
    # that only partly overlaps an earlier rule of another owner makes ownership depend on rule order:
    # that is the overlap validate reports, unless the later rule says "override": true.
    covers = {i: set() for i in range(len(rules))}
    resolved = []
    for target, label in items:
        owner, win, matches = owner_of(plan, target)
        resolved.append((target, label, owner, win, matches))
        for m in matches:
            covers[m].add(label)
    reported = set()
    for target, label, owner, win, matches in resolved:
        for m in matches:
            hits[m] += 1
        if owner is None:
            E(f"{label}: no owner rule matches it")
            continue
        wins[win] += 1
        if rules[win].get("override"):
            continue
        for m in matches:
            if m == win or rules[m].get("owner") == owner or covers[win] <= covers[m] or (m, win) in reported:
                continue
            reported.add((m, win))
            extra = sorted(covers[win] - covers[m])[:2]
            E(f"owner rules {m + 1} ({rules[m]['pattern']} -> {rules[m]['owner']}) and {win + 1} "
              f"({rules[win]['pattern']} -> {owner}) partly overlap, e.g. on {label}; rule {win + 1} also takes "
              f"{', '.join(extra)}, which rule {m + 1} does not cover, so ownership depends on rule order. "
              f"Narrow one rule, or mark rule {win + 1} \"override\": true if that is intended.")
    for i, r in enumerate(rules):
        if hits[i] == 0:
            W(f"owner rule {i + 1} ({r.get('pattern')} -> {r.get('owner')}) matches no planned file or pattern")
        elif wins[i] == 0:
            W(f"owner rule {i + 1} ({r.get('pattern')} -> {r.get('owner')}) never wins: later rules override every match")

    # AgenticTeam roster check
    if team is not None:
        agents = {a.get("id"): a for a in team.get("agents", [])}
        owners_used = {owner_of(plan, t)[0] for t, _ in items} - {None}
        for r in plan["roster"]:
            if r.get("kind") != "agent" or (r.get("harness") or "").lower() not in ("agenticteam", "agentic-team"):
                continue
            a = agents.get(r["id"])
            if not a:
                E(f"roster {r['id']}: not an agent in team.json")
            elif r["id"] in owners_used and a.get("access") not in WRITE_ACCESS:
                E(f"roster {r['id']}: owns files but its AgenticTeam access is {a.get('access')!r}, not workspace-write")
    return errors, warnings


def cmd_validate(args):
    root = find_root(args.root)
    plan = load_plan(root)
    team = None
    if args.team:
        team = read_json(Path(args.team))
        if team is None:
            die(f"team file not found: {args.team}")
    errors, warnings = validate_plan(plan, team)
    for w in warnings:
        print("warning:", w)
    for e in errors:
        print("error:", e)
    n_files, n_pat = len(plan["files"]), len(plan["patterns"])
    if errors:
        print(f"\n{len(errors)} error(s), {len(warnings)} warning(s). The blueprint is not ready.")
        sys.exit(1)
    print(f"OK: {n_files} files, {n_pat} patterns, {len(plan['modules'])} modules, "
          f"{len(plan['phases'])} phases, {len(plan['roster'])} owners. {len(warnings)} warning(s).")


# ----------------------------------------------------------------------------- disk scan and status

def repo_files(root, plan):
    ignore = DEFAULT_IGNORE + list(plan.get("ignore", []))
    files = None
    try:
        out = subprocess.run(["git", "ls-files", "--cached", "--others", "--exclude-standard", "-z"],
                             cwd=root, capture_output=True, timeout=60)
        if out.returncode == 0:
            files = [norm(p) for p in out.stdout.decode("utf-8", "replace").split("\0") if p]
    except (OSError, subprocess.SubprocessError):
        files = None
    if files is None:
        files = []
        for dirpath, dirnames, filenames in os.walk(root):
            rel_dir = norm(os.path.relpath(dirpath, root))
            rel_dir = "" if rel_dir == "." else rel_dir
            dirnames[:] = [d for d in dirnames if not any(glob_match(g, (rel_dir + "/" if rel_dir else "") + d + "/x") for g in ignore)]
            for fn in filenames:
                files.append((rel_dir + "/" if rel_dir else "") + fn)
    return sorted(p for p in files if (root / p).is_file() and not any(glob_match(g, p) for g in ignore))


def git_head(root):
    try:
        out = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=root, capture_output=True, timeout=20)
        return out.stdout.decode().strip() or None if out.returncode == 0 else None
    except (OSError, subprocess.SubprocessError):
        return None


def effective_status(root, plan, state, f):
    rec = state["files"].get(f["path"], {})
    present = (root / f["path"]).is_file()
    if f.get("action") == "delete":
        return ("verified" if not present else (rec.get("state") if rec.get("state") in ("claimed", "blocked") else "planned")), present
    if rec.get("state") == "blocked":
        return "blocked", present
    if not present:
        return ("claimed" if rec.get("state") == "claimed" else "planned"), present
    ver = rec.get("verified") or {}
    if ver.get("ok") and ver.get("sha") and ver["sha"] == file_sha(root / f["path"]):
        return "verified", present
    if rec.get("state") in ("built", "verified"):
        return "built", present
    return "ondisk", present


def compute(root, plan, state):
    """Everything the views need, in one dict."""
    rows = []
    for f in plan["files"]:
        st, present = effective_status(root, plan, state, f)
        owner, rule, _ = owner_of(plan, f["path"])
        rec = state["files"].get(f["path"], {})
        rows.append({"path": f["path"], "kind": "file", "action": f.get("action"), "module": f.get("module"),
                     "phase": f.get("phase"), "purpose": f.get("purpose", ""), "owner": owner, "rule": rule,
                     "contract": bool(f.get("contract")), "status": st, "present": present,
                     "consumes": f.get("consumes", []), "produces": f.get("produces", []),
                     "dependsOn": [norm(d) for d in f.get("dependsOn", [])], "verify": item_verify(plan, f),
                     "ac": f.get("ac", []), "by": rec.get("by"), "at": rec.get("at"), "note": rec.get("note")})
    pats = []
    for p in plan["patterns"]:
        owner, rule, _ = owner_of(plan, p.get("glob", ""))
        inst = state.get("patterns", {}).get(p.get("id"), {}).get("instances", [])
        pats.append({"id": p.get("id"), "glob": p.get("glob"), "module": p.get("module"), "phase": p.get("phase"),
                     "purpose": p.get("purpose", ""), "instance": p.get("instance", ""), "owner": owner, "rule": rule,
                     "examples": p.get("examples", []), "instances": inst, "verify": item_verify(plan, p)})
    counts = {s: 0 for s in STATES}
    for r in rows:
        counts[r["status"]] += 1
    return {"rows": rows, "patterns": pats, "counts": counts}


def summarize(rows, key):
    out = {}
    for r in rows:
        k = r.get(key) or "(none)"
        d = out.setdefault(k, {s: 0 for s in STATES})
        d[r["status"]] += 1
    return out


def cmd_sync(args):
    root = find_root(args.root)
    plan = load_plan(root)
    state = load_state(root)
    disk = repo_files(root, plan)
    disk_set = set(disk)
    planned = {f["path"] for f in plan["files"]}
    module_readmes = {norm(m.get("path", "")).rstrip("/") + "/README.md" for m in plan["modules"] if m.get("path")}
    pat_rx = [(p.get("id"), pattern_instance_rx(p.get("glob", ""))) for p in plan["patterns"] if p.get("glob")]
    patterns = {pid: {"instances": []} for pid, _ in pat_rx}
    unplanned = []
    for p in disk:
        if p in planned or p in module_readmes:
            continue
        hit = False
        for pid, rx in pat_rx:
            if rx.match(p):
                patterns[pid]["instances"].append(p)
                hit = True
                break
        if not hit:
            unplanned.append(p)
    missing_modify = [f["path"] for f in plan["files"] if f.get("action") == "modify" and f["path"] not in disk_set]
    state["patterns"] = patterns
    state["unplanned"] = unplanned
    state["missingModify"] = missing_modify
    state["syncedAt"] = now_iso()
    state["head"] = git_head(root)
    save_state(root, state)
    comp = compute(root, plan, state)
    c = comp["counts"]
    append_log(root, {"event": "sync", "head": state["head"], "counts": c, "unplanned": len(unplanned)})
    if not args.quiet:
        print(f"Synced {len(disk)} files on disk against {len(plan['files'])} planned files and {len(plan['patterns'])} patterns.")
        print("  " + "  ".join(f"{GLYPH[s]} {LABEL[s]} {c[s]}" for s in STATES))
        if unplanned:
            print(f"  Unplanned files (drift): {len(unplanned)}")
            for p in unplanned[:15]:
                print("    +", p)
            if len(unplanned) > 15:
                print(f"    ... and {len(unplanned) - 15} more (see map.html, Drift)")
        if missing_modify:
            print(f"  Planned to modify but missing: {len(missing_modify)}")
            for p in missing_modify[:10]:
                print("    !", p)
    if not args.no_render:
        errors, _ = validate_plan(plan)
        if errors:
            if not args.quiet:
                print(f"  Views not refreshed: the blueprint has {len(errors)} validation error(s). Run validate.")
        else:
            render_all(root, plan, state, quiet=True)
    if getattr(args, "strict", False) and (unplanned or missing_modify):
        sys.exit(1)


def cmd_status(args):
    root = find_root(args.root)
    plan = load_plan(root)
    state = load_state(root)
    comp = compute(root, plan, state)
    rows = comp["rows"]
    if args.owner:
        rows = [r for r in rows if r["owner"] == args.owner]
    if args.phase:
        rows = [r for r in rows if r["phase"] == args.phase]
    if args.json:
        print(json.dumps({"rows": rows, "patterns": comp["patterns"], "unplanned": state.get("unplanned", []),
                          "syncedAt": state.get("syncedAt")}, indent=2, ensure_ascii=False))
        return
    total = len(rows)
    done = sum(1 for r in rows if r["status"] == "verified")
    built = sum(1 for r in rows if r["status"] in ("built", "verified"))
    print(f"{plan['app'].get('name')}: {total} planned files"
          + (f" for {args.owner}" if args.owner else "") + (f" in {args.phase}" if args.phase else ""))
    print(f"  verified {done}/{total}, built or better {built}/{total}. Last sync: {state.get('syncedAt') or 'never'}")
    print("\n  By phase:")
    for ph in plan["phases"]:
        d = summarize([r for r in rows if r["phase"] == ph["id"]], "phase").get(ph["id"])
        if d:
            n = sum(d.values())
            print(f"    {ph['id']:<4} {ph.get('name', ''):<28} " + " ".join(f"{GLYPH[s]}{d[s]}" for s in STATES if d[s]) + f"  ({d['verified']}/{n} verified)")
    if not args.owner:
        print("\n  By owner:")
        for o, d in sorted(summarize(rows, "owner").items()):
            n = sum(d.values())
            print(f"    {o:<28} " + " ".join(f"{GLYPH[s]}{d[s]}" for s in STATES if d[s]) + f"  ({d['verified']}/{n} verified)")
    blocked = [r for r in rows if r["status"] == "blocked"]
    if blocked:
        print("\n  Blocked:")
        for r in blocked:
            print(f"    ▲ {r['path']} ({r['owner']}): {r.get('note') or ''}")
    if args.next:
        ready = next_ready(plan, comp["rows"], args.owner)
        print("\n  Ready to build next:")
        for r in ready[:20]:
            print(f"    {r['path']}  ({r['owner']}, {r['phase']})")
        if not ready:
            print("    nothing: everything in the current phase is claimed, built or waiting on a dependency")


def next_ready(plan, rows, owner=None):
    pidx = phase_index(plan)
    by_path = {r["path"]: r for r in rows}
    open_rows = [r for r in rows if r["status"] in ("planned", "claimed", "ondisk")]
    if not open_rows:
        return []
    current = min(pidx.get(r["phase"], 99) for r in open_rows)
    ready = []
    for r in open_rows:
        if pidx.get(r["phase"], 99) != current or (owner and r["owner"] != owner):
            continue
        deps = [by_path.get(d) for d in r["dependsOn"]]
        if all(d is None or d["status"] in ("built", "verified") for d in deps):
            ready.append(r)
    return sorted(ready, key=lambda r: r["path"])


